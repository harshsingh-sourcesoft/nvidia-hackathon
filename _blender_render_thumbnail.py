"""
Internal helper invoked by generate_thumbnails.py, not meant to be run
directly. Renders a single .glb to a transparent-background PNG catalog
thumbnail: imports the model, frames a 3/4 "hero shot" camera around its
bounding box, adds simple two-light studio lighting, and renders.

Usage (called by generate_thumbnails.py):
  blender --background --factory-startup --python _blender_render_thumbnail.py -- <in.glb> <out.png>
"""
import bpy
import sys
import math
import mathutils

argv = sys.argv[sys.argv.index("--") + 1:]
in_glb, out_png = argv[0], argv[1]

# ── Clear the factory-startup scene (default cube/camera/light) ───────────
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)

# ── Import ──────────────────────────────────────────────────────────────
bpy.ops.import_scene.gltf(filepath=in_glb)
imported = [o for o in bpy.context.scene.objects if o.type == 'MESH']
if not imported:
    print(f"[thumb] NO_MESH {in_glb}")
    sys.exit(1)

# ── Combined world-space bounding box of everything imported ──────────────
mins = [float('inf')] * 3
maxs = [-float('inf')] * 3
for obj in imported:
    for corner in obj.bound_box:
        world = obj.matrix_world @ mathutils.Vector(corner)
        for i in range(3):
            mins[i] = min(mins[i], world[i])
            maxs[i] = max(maxs[i], world[i])
center = mathutils.Vector([(mins[i] + maxs[i]) / 2 for i in range(3)])
size = mathutils.Vector([maxs[i] - mins[i] for i in range(3)])
radius = max(size.length / 2, 0.05)

# ── Camera: 3/4 "hero" angle, distance auto-framed from the bbox ──────────
cam_data = bpy.data.cameras.new("ThumbCam")
cam_obj = bpy.data.objects.new("ThumbCam", cam_data)
bpy.context.scene.collection.objects.link(cam_obj)
direction = mathutils.Vector((1.0, -1.4, 0.9)).normalized()
distance = radius / math.tan(cam_data.angle / 2) * 1.35
cam_obj.location = center + direction * distance
cam_obj.rotation_euler = (center - cam_obj.location).to_track_quat('-Z', 'Y').to_euler()
bpy.context.scene.camera = cam_obj

# ── Broken-texture fallback ─────────────────────────────────────────────
# Some source GLBs embed texture data Blender's image loader can't decode
# (reports size (0,0)) - importing one leaves Blender's glaring magenta
# "missing texture" indicator on the whole model instead of a real render.
# Detect that and substitute a uniform neutral "clay" material for the
# whole render instead, so the thumbnail still shows the model's actual
# shape/silhouette cleanly rather than an unusable magenta blob.
# IMPORTANT: only check source=='FILE' images (the ones actually imported
# from the GLB) - bpy.data.images always also contains Blender's own
# internal compositor placeholders ("Render Result", "Viewer Node"), which
# are legitimately (0,0) before anything has been rendered yet. Checking
# ALL images (as this used to) matched those every single time regardless
# of the model's real textures, so every thumbnail ever generated by this
# script silently used the gray clay fallback even when nothing was broken.
if any(img.size[0] == 0 for img in bpy.data.images if img.source == 'FILE'):
    print(f"[thumb] WARN broken texture(s) in {in_glb} - using clay fallback material")
    clay = bpy.data.materials.new("ClayFallback")
    clay.use_nodes = True
    bsdf = clay.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = (0.72, 0.72, 0.75, 1)
        bsdf.inputs["Roughness"].default_value = 0.55
    # Direct per-object material replacement - a view_layer.material_override
    # was tried first but isn't reliably honored under Eevee Next, so assign
    # the fallback straight onto each mesh's material slots instead.
    for obj in imported:
        obj.data.materials.clear()
        obj.data.materials.append(clay)

# ── Lighting: angled key + dim opposite fill, plus soft world ambient ─────
key_data = bpy.data.lights.new("KeyLight", type='SUN')
key_data.energy = 3.0
key_obj = bpy.data.objects.new("KeyLight", key_data)
key_obj.rotation_euler = (math.radians(55), 0, math.radians(35))
bpy.context.scene.collection.objects.link(key_obj)

fill_data = bpy.data.lights.new("FillLight", type='SUN')
fill_data.energy = 1.0
fill_obj = bpy.data.objects.new("FillLight", fill_data)
fill_obj.rotation_euler = (math.radians(65), 0, math.radians(-150))
bpy.context.scene.collection.objects.link(fill_obj)

world = bpy.context.scene.world
if world is None:
    world = bpy.data.worlds.new("ThumbWorld")
    bpy.context.scene.world = world
world.use_nodes = True
bg = world.node_tree.nodes.get("Background")
if bg:
    bg.inputs[0].default_value = (0.9, 0.9, 0.92, 1)
    bg.inputs[1].default_value = 0.5

# ── Render settings ─────────────────────────────────────────────────────
scene = bpy.context.scene
engine_items = {e.identifier for e in bpy.types.RenderSettings.bl_rna.properties['engine'].enum_items}
scene.render.engine = 'BLENDER_EEVEE_NEXT' if 'BLENDER_EEVEE_NEXT' in engine_items else 'BLENDER_EEVEE'
scene.render.resolution_x = 512
scene.render.resolution_y = 512
scene.render.film_transparent = True
scene.render.image_settings.file_format = 'PNG'
scene.render.image_settings.color_mode = 'RGBA'
scene.render.filepath = out_png

bpy.ops.render.render(write_still=True)
print(f"[thumb] DONE {out_png}")
